"""Market-data service — the single seam between the UI backend and nTrade.

Design goals (per docs/superpowers/specs/2026-08-02-trading-ui-design.md):
  * The UI must never depend on a particular broker API. Every REST route and
    the live candle pump talk to :class:`MarketDataService`, which delegates
    candle/quote reads to a :class:`CandleProvider`.
  * Instrument metadata (roots, futures contracts, expiries) is real Dhan
    instrument-master data (the daily ``all_instrument*.csv`` dumps that
    already ship in this repo) parsed by :class:`FuturesMaster`.
  * Candles are normalized to the frontend candle DTO::

        {"time": int_utc_epoch_seconds, "open": f, "high": f,
         "low": f, "close": f, "volume": int}

Providers
  * ``DhanProvider``    — live broker (needs ``.env`` Dhan credentials).
  * ``ParquetProvider`` — offline ``ParquetStorage`` reads.
  * ``SyntheticProvider`` — deterministic seeded OHLCV for local dev / replay
    demos / tests (uses the same session-grid + walk family as the sim layer).
"""

