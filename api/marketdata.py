# IST market session: 09:15–15:30. Bars are generated on this grid and then
# converted to UTC epoch seconds for the wire.
_SESSION_TZ = ZoneInfo("Asia/Kolkata")
_SESSION_OPEN = time(9, 15)
_SESSION_CLOSE = time(15, 30)
_SESSION_MINUTES = 375  # 09:15 → 15:30

# UI interval -> session bar span in minutes (1D = one bar per session day).
# Keyed by the exact wire strings the REST layer accepts (not the Timeframe
# enum values, which are lowercase and would miss "1D").
_INTERVAL_MINUTES = {"1m": 1, "5m": 5, "15m": 15, "1h": 60, "1D": 375}
VALID_INTERVALS = tuple(_INTERVAL_MINUTES)

# Deterministic "base" anchor prices for well-known roots (synthetic provider);
# unknown roots get a hash-derived anchor in the same band.
_KNOWN_BASE = {"NIFTY": 24800.0, "BANKNIFTY": 55500.0, "FINNIFTY": 23200.0,
               "MIDCPNIFTY": 12600.0, "SENSEX": 81500.0}

# 90 calendar days of 1m MCX (09:00–23:30) is ~78k bars if every day traded.
MAX_CANDLES_LIMIT = 100_000
def _base_price(root: str) -> float:
    """Deterministic synthetic anchor price for ``root`` (a known index root
    or any symbol). Canonical formula shared by every synthetic source so the
    same symbol anchors identically regardless of code path."""
    if root in _KNOWN_BASE:
        return _KNOWN_BASE[root]
    digest = int.from_bytes(hashlib.md5(root.encode()).digest()[:8], "big")
    return round(15_000.0 + (digest % 55_000) / 10.0, 2)


DEFAULT_DAYS = 8  # synthetic sessions generated by default
LIVE_HISTORY_DAYS = 90  # raw DhanProvider with no dates (backfill / tests)
CHART_DAYS = 3  # UI + MarketDataService default window (weekdays, IST)
# Cap on how far back SyntheticProvider will lazily extend its session grid
# when a request asks for a wider window. Mirrors the Dhan provider's
# 90-calendar-day history horizon; requests older than this return empty
# (the same no-data contract as the real providers).
MAX_SYNTH_SESSIONS = 90
# Ceiling on synthesized replay ticks per request. Ticks ride the compact
# per-bar wire format (prices/quantities arrays), so a full 1m contract
# history (~19k bars x 60 ticks) is only ~10MB of JSON — well under this.
MAX_TICKS = 1_500_000


