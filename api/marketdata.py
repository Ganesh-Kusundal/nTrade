class MarketDataService:
    """Composition root: instrument master + one candle/quote provider."""

    def __init__(self, provider: CandleProvider, master: FuturesMaster | None = None):
        self.provider = provider
        self.master = master or FuturesMaster()

    @property
    def name(self) -> str:
        return self.provider.name

    # ------------------------------------------------------------------ meta
    def describe(self) -> dict:
        return {
            "provider": self.name,
            "instrument_master_loaded": self.master.loaded,
            "instrument_master_source": str(self.master.source_path)
            if self.master.source_path else None,
            "live": self.name == "dhan",
            "roots": self.roots(),
        }

    def roots(self) -> list[dict]:
        today = date.today()
        out = []
        # master.roots() puts index futures first, then commodity/other.
        for root in self.master.roots():
            if root not in SUPPORTED_ROOTS:
                continue  # terminal's curated universe only
            contracts = self.master.contracts(root)
            front = self.master.front_month(root)
            out.append({
                "root": root,
                "exchange": front.exchange if front else Exchange.DERIVATIVES,
                "display_name": f"{root} Futures",
                "n_contracts": len(contracts),
                "front_month": front.as_dict(today=today) if front else None,
            })
        return out

    def contracts(self, root: str) -> list[dict]:
        today = date.today()
        front = self.master.front_month(root)
        front_id = front.contract_id if front else None
        return [c.as_dict(today=today, is_front_month=c.contract_id == front_id)
                for c in self.master.contracts(root)]

    def has_root(self, root: str) -> bool:
        return bool(self.master.contracts(root))

    # ------------------------------------------------------------------ data
    def candles(self, *, symbol: str, exchange: str = Exchange.DERIVATIVES,
                interval: str = Timeframe.MIN, start: datetime | None = None,
                end: datetime | None = None, limit: int | None = None) -> list[dict]:
        if end is None:
            end = datetime.now(tz=_SESSION_TZ)
        if start is None:
            start = chart_start(end)
        rows = self.provider.candles(symbol=symbol, exchange=exchange,
                                     interval=interval, start=start, end=end,
                                     limit=limit)
        lo, hi = start.timestamp(), end.timestamp()
        rows = [c for c in rows if lo <= c["time"] <= hi]
        # Dhan history ships bars that start after the session close (1m to
        # 15:39, 5m to 15:35 on NSE) while the live pump stops exactly at the
        # close — those ghost bars break the right-edge seam after the
        # historical load. Strip them so history matches the live grid.
        rows = _clamp_to_session(rows, exchange=exchange, interval=interval)
        if limit is not None and len(rows) > limit:
            rows = rows[-limit:]
        return rows

    def ticks(self, *, symbol: str, exchange: str = Exchange.DERIVATIVES,
              interval: str = Timeframe.MIN, start: datetime | None = None,
              end: datetime | None = None, limit: int | None = None) -> list[dict]:
        """Replay ticks for a symbol/range.

        For the ``synthetic`` provider the ticks are synthesized from the
        provider's candles (deterministic, seeded per bar). Every other
        provider serves the *recorded* real ticks written by the live pump
        (JSONL), so replay reflects what was actually traded, not an
        extrapolation.

        The wire format is compact — one entry per bar with ``prices`` /
        ``quantities`` arrays (tick i of a bar is at ``bar.time + i``) — so a
        full contract history fits in a few MB of JSON.

        When the window exceeds the tick budget (``MAX_TICKS``), the FIRST
        bars are kept — replay starts at bar 0, so that is where the intra-bar
        animation is watched. Bars beyond the budget have no ticks and the
        client falls back to plain bars for them.
        """
        if self.name != "synthetic":
            return self._recorded_ticks(symbol, interval, start, end)
        rows = self.candles(symbol=symbol, exchange=exchange, interval=interval,
                            start=start, end=end, limit=limit)
        if not rows:
            return []
        span_s = _INTERVAL_MINUTES.get(interval, 1) * 60  # one tick per second
        max_bars = max(0, MAX_TICKS // span_s)
        if len(rows) > max_bars:
            rows = rows[:max_bars]
        from ntrade.sim.tick_simulator import synthesize_1m_ticks

        out: list[dict] = []
        for r in rows:
            bar_ts = datetime.fromtimestamp(r["time"], tz=timezone.utc)
            seed = int.from_bytes(hashlib.md5(f"{symbol}|{r['time']}".encode()).digest()[:8], "big")
            tks = synthesize_1m_ticks(bar_ts, r["open"], r["high"], r["low"],
                                      r["close"], r["volume"],
                                      seed=seed, seconds=span_s)
            out.append({"time": r["time"],
                        "prices": [float(t.price) for t in tks],
                        "quantities": [int(t.quantity) for t in tks]})
        return out

    def _recorded_ticks(self, symbol: str, interval: str,
                        start: datetime | None, end: datetime | None) -> list[dict]:
        """Group recorded JSONL ticks into the per-bar replay wire format."""
        base = Path(os.environ.get("NTRADE_TICKS_DIR", "data/ticks"))
        span_s = _INTERVAL_MINUTES.get(interval, 1) * 60
        bars: dict[int, dict] = {}
        # Naive start/end are IST wall-clock (the route's contract) — pin them
        # so .timestamp() is the correct epoch regardless of machine tz.
        if start is not None and start.tzinfo is None:
            start = start.replace(tzinfo=_SESSION_TZ)
        if end is not None and end.tzinfo is None:
            end = end.replace(tzinfo=_SESSION_TZ)
        start_ts = start.timestamp() if start else None
        end_ts = end.timestamp() if end else None
        lo_date = (start or datetime.now(tz=_SESSION_TZ)).date()
        hi_date = end.date() if end else lo_date
        d = lo_date
        while d <= hi_date:
            p = base / symbol / f"{d:%Y-%m-%d}.jsonl"
            d += timedelta(days=1)
            if not p.exists():
                continue
            for line in p.read_text().splitlines():
                try:
                    rec = json.loads(line)
                    ts = datetime.fromisoformat(rec["ts"]).timestamp()
                    if start_ts is not None and ts < start_ts:
                        continue
                    if end_ts is not None and ts > end_ts:
                        continue
                    b = int(ts) - (int(ts) % span_s)
                    entry = bars.setdefault(b, {"time": b, "prices": [], "quantities": []})
                    entry["prices"].append(float(rec["price"]))
                    entry["quantities"].append(int(rec["qty"]))
                except Exception:  # noqa: BLE001
                    continue
        return [bars[k] for k in sorted(bars)]

    def quote(self, *, symbol: str, exchange: str = Exchange.DERIVATIVES) -> dict:
        return self.provider.quote(symbol=symbol, exchange=exchange)


def build_service(provider: str | None = None, env: dict | None = None,
                  master: FuturesMaster | None = None) -> MarketDataService:
    """Build a service for ``provider`` (env ``NTRADE_MARKET_PROVIDER``).

    Supported: ``dhan`` (live), ``parquet`` (offline store), ``synthetic``
    (deterministic offline — explicit opt-in only, never a silent default).

    Raises :class:`MarketDataError` when no provider is configured so the
    server can never silently serve fabricated data.
    """
    env = env if env is not None else os.environ
    name = (provider or env.get("NTRADE_MARKET_PROVIDER") or "").strip().lower()
    if not name:
        raise MarketDataError(
            "no market provider configured: set NTRADE_MARKET_PROVIDER or "
            "pass --provider (dhan|parquet|synthetic)"
        )
    master = master or FuturesMaster()
    if name == "dhan":
        service = MarketDataService(DhanProvider(master, env=env), master=master)
    elif name == "parquet":
        base = env.get("NTRADE_DATA_DIR", "data/ohlcv")
        service = MarketDataService(ParquetProvider(master, base_path=base), master=master)
    elif name == "synthetic":
        service = MarketDataService(SyntheticProvider(master), master=master)
    else:
        raise MarketDataError(
            f"unknown market provider {name!r} (use dhan|parquet|synthetic)"
        )
    return service


