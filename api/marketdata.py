def chart_start(now: datetime | None = None, days: int = CHART_DAYS) -> datetime:
    """Midnight IST of the Nth weekday, inclusive of today. Matches UI chartStartIst.

    # ponytail: weekdays only; no holiday calendar — a holiday shrinks the window
    """
    now = now or datetime.now(tz=_SESSION_TZ)
    if now.tzinfo is None:
        now = now.replace(tzinfo=_SESSION_TZ)
    else:
        now = now.astimezone(_SESSION_TZ)
    d = now.date()
    kept = 0
    start = d
    # The backward scan needs enough calendar days to find `days` weekdays
    # (5/7 ratio + weekend slack) — the old fixed 21-day cap silently
    # truncated any window wider than ~15 weekdays. ceil(7*days/5) matches
    # the UI's chartStartIst exactly.
    budget = max(21, (days * 7 + 4) // 5 + 2)
    for _ in range(budget):
        if d.weekday() < 5:
            kept += 1
            start = d
            if kept >= max(1, days):
                break
        d -= timedelta(days=1)
    return datetime.combine(start, time.min, tzinfo=_SESSION_TZ)


def parse_iso(value: str | None, field: str = "timestamp") -> datetime | None:
    """Parse an ISO-8601 timestamp param (naive -> IST, per domain convention)."""
    if value is None or not value.strip():
        return None
    try:
        dt = datetime.fromisoformat(value.strip())
    except ValueError as exc:
        raise ValueError(f"invalid {field}: {value!r} (expected ISO-8601)") from exc
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=_SESSION_TZ)
    return dt


def _f(v) -> float:
    try:
        return float(v or 0.0)
    except (TypeError, ValueError):
        return 0.0


def _int_or_none(v) -> int | None:
    try:
        return int(float(v))
    except (TypeError, ValueError):
        return None


