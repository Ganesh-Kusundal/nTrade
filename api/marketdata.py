# --------------------------------------------------------------------------- DTOs


@dataclass(frozen=True)
class Candle:
    """Normalized candle DTO — ``time`` is UTC epoch seconds."""

    time: int
    open: float
    high: float
    low: float
    close: float
    volume: int

    def as_dict(self) -> dict:
        return {"time": self.time, "open": self.open, "high": self.high,
                "low": self.low, "close": self.close, "volume": self.volume}


def candle_from_row(row: dict) -> Candle | None:
    """Build a Candle from a normalized OHLCV row dict (lowercase keys)."""
    try:
        ts = row["timestamp"]
        if isinstance(ts, datetime):
            dt = ts
        else:
            dt = datetime.fromisoformat(str(ts))
    except (KeyError, TypeError, ValueError):
        return None
    if dt.tzinfo is None:
        # Domain convention: naive timestamps are IST wall time (parquet store
        # strips tz; Dhan ships tz-aware). Interpret naive as IST before
        # converting to UTC epoch so the wire time is unambiguous.
        dt = dt.replace(tzinfo=_SESSION_TZ)
    else:
        dt = dt.astimezone(timezone.utc)
    return Candle(
        time=int(dt.timestamp()),
        open=float(row.get("open") or 0.0),
        high=float(row.get("high") or 0.0),
        low=float(row.get("low") or 0.0),
        close=float(row.get("close") or 0.0),
        volume=int(row.get("volume") or 0),
    )


def normalize_candles(rows: list[dict] | list[Candle], *, limit: int | None = None) -> list[dict]:
    """Sort + dedupe (by time) + clamp a raw candle list to the wire shape."""
    candles: list[Candle] = []
    seen: set[int] = set()
    for row in rows:
        c = row if isinstance(row, Candle) else candle_from_row(row)
        if c is None or c.time in seen:
            continue
        seen.add(c.time)
        candles.append(c)
    candles.sort(key=lambda c: c.time)
    if limit is not None and len(candles) > limit:
        candles = candles[-limit:]
    return [c.as_dict() for c in candles]


# ------------------------------------------------------------------ instrument master


@dataclass(frozen=True)
class Contract:
    """A futures contract as advertised by the instrument master."""

    contract_id: str          # Dhan trading symbol, e.g. "NIFTY-Oct2026-FUT"
    symbol: str               # Dhan custom symbol, e.g. "NIFTY OCT FUT"
    root: str
    exchange: str
    expiry: date
    lot_size: float
    tick_size: float
    security_id: int | None
    instrument_name: str = ""  # FUTIDX (index) / FUTSTK (stock) / FUTCOM ...

    def as_dict(self, *, today: date | None = None, is_front_month: bool = False) -> dict:
        today = today or date.today()
        dte = (self.expiry - today).days
        return {
            "contract_id": self.contract_id,
            "symbol": self.symbol,
            "root": self.root,
            "exchange": self.exchange,
            "expiry": self.expiry.isoformat(),
            "days_to_expiry": dte,
            "is_expired": dte < 0,
            "is_front_month": is_front_month,
            "lot_size": self.lot_size,
            "tick_size": self.tick_size,
            "security_id": self.security_id,
        }

    @property
    def is_index(self) -> bool:
        return self.instrument_name == "FUTIDX"


def _glob_instrument_csvs() -> list[Path]:
    """Locate Dhan instrument dumps (repo root + Dependencies/, newest first).

    The downloads historically land as ``Dependencies\\all_instrument
    YYYY-MM-DD.csv`` (Windows-style backslash in the *filename*, at the repo
    root) — glob with a tolerant pattern that also covers a real
    ``Dependencies/`` directory.
    """
    root = Path(__file__).resolve().parent.parent
    candidates: list[Path] = []
    for pattern in ("*all_instrument*.csv", "*all_instrument*"):
        candidates.extend(p for p in root.glob(pattern) if p.is_file())
    deps_dir = root / "Dependencies"
    if deps_dir.is_dir():
        candidates.extend(p for p in deps_dir.glob("*all_instrument*.csv") if p.is_file())
    # De-duplicate by resolved path and keep newest-modified first.
    # Skip empty dumps (Tradehull sometimes creates a 0-byte file before
    # the download finishes / when the fetch fails).
    seen: set[str] = set()
    out: list[Path] = []
    for p in sorted(candidates, key=lambda p: p.stat().st_mtime, reverse=True):
        if p.stat().st_size <= 0:
            continue
        key = str(p.resolve())
        if key not in seen:
            seen.add(key)
            out.append(p)
    return out


class FuturesMaster:
    """Parsed Dhan instrument master — futures contracts by root symbol."""

    def __init__(self, csv_path: str | Path | None = None):
        self.source_path: Path | None = None
        self._contracts: dict[str, list[Contract]] = {}
        candidates = [Path(csv_path)] if csv_path is not None else _glob_instrument_csvs()
        for path in candidates:
            if not path.exists() or path.stat().st_size <= 0:
                continue
            try:
                self._load(path)
                return
            except Exception:
                # Corrupt/truncated dump — try the next newest file.
                self.source_path = None
                self._contracts = {}
                continue

    # ------------------------------------------------------------------ load
    def _load(self, path: Path) -> None:
        self.source_path = path
        by_root: dict[str, list[Contract]] = {}
        seen_ids: set[str] = set()
        with open(path, newline="", encoding="utf-8-sig") as fh:
            reader = csv.reader(fh)
            header = next((r for r in reader if r and r[1] == "SEM_EXM_EXCH_ID"), None)
            if header is None:
                raise MarketDataError(f"instrument master has no header: {path}")
            idx = {name: i for i, name in enumerate(header)}
            exch_col = idx.get("SEM_EXM_EXCH_ID")
            for row in reader:
                if len(row) < len(header):
                    continue
                inst_type = row[idx["SEM_EXCH_INSTRUMENT_TYPE"]].strip().upper()
                # Index/stock F&O dumps use FUT; MCX commodity futures use FUTCOM.
                if inst_type not in ("FUT", "FUTCOM"):
                    continue
                custom = row[idx["SEM_CUSTOM_SYMBOL"]].strip().upper()
                trading = row[idx["SEM_TRADING_SYMBOL"]].strip()
                if not custom or not trading or " " not in custom:
                    continue
                root = custom.split(" ", 1)[0]
                try:
                    expiry = datetime.strptime(
                        row[idx["SEM_EXPIRY_DATE"]].strip(), "%Y-%m-%d %H:%M:%S"
                    ).date()
                except ValueError:
                    continue
                contract_id = trading
                if contract_id in seen_ids:
                    continue
                seen_ids.add(contract_id)
                exch_id = row[exch_col].strip().upper() if exch_col is not None else ""
                exchange = Exchange.MCX if exch_id == "MCX" else Exchange.DERIVATIVES
                by_root.setdefault(root, []).append(Contract(
                    contract_id=contract_id,
                    symbol=custom,
                    root=root,
                    exchange=exchange,
                    expiry=expiry,
                    lot_size=_f(row[idx["SEM_LOT_UNITS"]]),
                    tick_size=_f(row[idx["SEM_TICK_SIZE"]]),
                    security_id=_int_or_none(row[idx["SEM_SMST_SECURITY_ID"]]),
                    instrument_name=row[idx["SEM_INSTRUMENT_NAME"]].strip().upper(),
                ))
        # Keep only roots with a futures contract set, sorted by expiry
        self._contracts = {root: sorted(lst, key=lambda c: c.expiry)
                           for root, lst in by_root.items()}

    # ------------------------------------------------------------------ query
    @property
    def loaded(self) -> bool:
        return self.source_path is not None

    def roots(self) -> list[str]:
        """All root symbols, index futures (FUTIDX) first."""
        idx = sorted(r for r, lst in self._contracts.items()
                     if any(c.is_index for c in lst))
        others = sorted(r for r in self._contracts if r not in idx)
        return idx + others

    def futures_roots(self) -> list[str]:
        """Roots with any tradeable futures contract (index, stock, commodity)."""
        return sorted(self._contracts)

    def index_roots(self) -> list[str]:
        """Root symbols with index futures only (NIFTY, BANKNIFTY, ...)."""
        return sorted(r for r, lst in self._contracts.items()
                      if any(c.is_index for c in lst))

    def contracts(self, root: str) -> list[Contract]:
        return self._contracts.get(root.upper(), [])

    def resolve(self, symbol: str) -> Contract | None:
        """Resolve a UI symbol (custom/trading/``root EXPIRY`` form) to a contract."""
        symbol = symbol.strip().upper()
        for lst in self._contracts.values():
            for c in lst:
                if c.symbol == symbol or c.contract_id == symbol:
                    return c
        # "NIFTY 2026-10-27" / "NIFTY 27Oct26" style lookups
        parts = symbol.split()
        if len(parts) >= 2:
            root = parts[0]
            for c in self._contracts.get(root, []):
                if symbol in (f"{root} {c.expiry.isoformat()}", f"{root} {c.expiry:%d%b%y}"):
                    return c
        return None

    def front_month(self, root: str) -> Contract | None:
        """Nearest not-yet-expired contract (fall back to nearest overall)."""
        lst = self._contracts.get(root.upper(), [])
        if not lst:
            return None
        today = date.today()
        active = [c for c in lst if c.expiry >= today]
        return (active[0] if active else lst[0])


