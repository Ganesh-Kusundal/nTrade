class DhanProvider:
    """Real broker candles/quotes through the existing DhanBroker adapter."""

    name = "dhan"

    def __init__(self, master: FuturesMaster, env_path: str = ".env",
                 env: dict | None = None, data_dir: str | None = None):
        self._master = master
        self._env_path = env_path
        self._env = env
        # Parquet datalake root — the same store ParquetProvider reads, so
        # every fetched futures history is available offline.
        self._data_dir = data_dir or os.environ.get("NTRADE_DATA_DIR", "data/ohlcv")
        self._broker = None
        self._factory = None
        self._last_error: str | None = None

    # ------------------------------------------------------------------ auth
    @property
    def connected(self) -> bool:
        return self._broker is not None

    def _ensure(self) -> None:
        if self._broker is not None:
            return
        from ntrade.brokers.dhan import DhanBroker
        from ntrade.factories import InstrumentFactory
        try:
            broker = DhanBroker(env_path=self._env_path, env=self._env, connect=True)
            self._broker = broker
            self._factory = InstrumentFactory(broker=broker)
        except Exception as exc:  # auth/TOTP/network failures surface cleanly
            self._last_error = str(exc)
            raise MarketDataError(
                f"Dhan broker unavailable ({exc}); check .env credentials"
            ) from exc

    def feed_auth(self) -> tuple[str, str]:
        """Client-id + token for dhanhq MarketFeed (live UI ticks)."""
        self._ensure()
        tsl = self._broker.tsl
        return str(tsl.ClientCode), str(tsl.token_id)

    def _instrument(self, symbol: str) -> object:
        """Build the domain instrument for a symbol (Future when resolvable)."""
        contract = self._master.resolve(symbol)
        root = (contract.root if contract else symbol.split()[0]).upper()
        if contract is not None and contract.exchange == Exchange.MCX:
            underlying = self._factory.commodity(root)
        else:
            underlying = self._factory.index(root)
        if contract is None:
            return underlying
        return self._factory.future(underlying, contract.expiry)

    # ------------------------------------------------------------------ data
    def candles(self, *, symbol: str, exchange: str, interval: str,
                start: datetime | None = None, end: datetime | None = None,
                limit: int | None = None) -> list[dict]:
        self._ensure()
        # No dates → 90 calendar days through today (backfill / direct calls).
        # Chart/UI goes through MarketDataService, which fills a 3-weekday window.
        # get_historical_data ignores dates (post-filter only) and often stops
        # at the last completed session — use the dated endpoint.
        if end is None:
            end = datetime.now(tz=_SESSION_TZ)
        if start is None:
            start = end - timedelta(days=LIVE_HISTORY_DAYS)
        try:
            inst = self._instrument(symbol)
            series = self._broker.get_long_term_historical(
                inst, timeframe=interval, from_date=start, to_date=end,
            )
            df = series.to_dataframe() if hasattr(series, "to_dataframe") else series
        except Exception as exc:
            raise MarketDataError(f"Dhan history fetch failed: {exc}") from exc
        if df is None or df.empty:
            return []
        df = df.copy()
        df.columns = [str(c).lower() for c in df.columns]
        rows = normalize_candles(df.to_dict("records"))
        # Clamp before write-through so the parquet lake never stores the
        # post-close ghost bars either (offline reads then stay clean too).
        rows = _clamp_to_session(rows, exchange=exchange, interval=interval)
        if limit is not None and len(rows) > limit:
            rows = rows[-limit:]
        self._write_through(symbol=symbol, exchange=exchange, interval=interval,
                            kind=getattr(inst, "KIND", "future"), rows=rows)
        return rows

    def _write_through(self, *, symbol: str, exchange: str, interval: str,
                       kind: str, rows: list[dict]) -> None:
        """Persist fetched candles into the Parquet datalake (best-effort).

        Writes only supported futures roots (index + MCX commodity) into the
        same store :class:`ParquetProvider` reads, so broker history becomes
        available offline. Timestamps are stored as naive IST wall time — the
        parquet store's contract — and round-trip exactly to the wire's UTC
        epochs via :func:`candle_from_row`. A storage failure must never fail
        the request, so every failure is swallowed (logged).
        """
        if not rows:
            return
        contract = self._master.resolve(symbol)
        root = (contract.root if contract else symbol.split()[0]).upper()
        if contract is None or root not in SUPPORTED_ROOTS:
            return
        try:
            from ntrade.data.parquet_store import ParquetStorage

            ParquetStorage(self._data_dir).upsert(parquet_frame(
                symbol=symbol, exchange=exchange, interval=interval,
                kind=kind, rows=rows))
        except Exception as exc:  # cache write must never break the request
            log.warning("parquet write-through failed for %s: %s", symbol, exc)

    def quote(self, *, symbol: str, exchange: str) -> dict:
        self._ensure()
        try:
            inst = self._instrument(symbol)
            q = self._broker.get_quote(inst)
        except Exception as exc:
            raise MarketDataError(f"Dhan quote fetch failed: {exc}") from exc
        prev_close = float(q.prev_close or 0.0)
        ltp = float(q.ltp or 0.0)
        high = float(q.high or 0.0)
        low = float(q.low or 0.0)
        open_ = float(q.open or 0.0)
        volume = int(q.volume or 0)
        # Dhan's quote-data enrichment can fail silently (the transport
        # swallows the error), leaving OHLC/prev_close at zero while LTP and
        # volume still come through. Fall back to the provider's own daily
        # series so the terminal header never shows an all-zero OHLC or a
        # bogus +100% change.
        if not (high and low and open_ and prev_close):
            rows = self.candles(symbol=symbol, exchange=exchange,
                                interval=Timeframe.D1, limit=2)
            if rows:
                last = rows[-1]
                prev = rows[-2] if len(rows) > 1 else rows[-1]
                high = high or float(last["high"])
                low = low or float(last["low"])
                open_ = open_ or float(last["open"])
                prev_close = prev_close or float(prev["close"])
                volume = volume or int(last.get("volume") or 0)
        change = ltp - prev_close
        return {
            "symbol": symbol,
            "exchange": exchange,
            "ltp": round(ltp, 2),
            "change": round(change, 2),
            "change_pct": round((change / prev_close * 100.0) if prev_close else 0.0, 2),
            "high": round(high, 2),
            "low": round(low, 2),
            "open": round(open_, 2),
            "prev_close": round(prev_close, 2),
            "volume": volume,
            "oi": int(q.oi or 0),
            "source": self.name,
        }


def parquet_frame(*, symbol: str, exchange: str, interval: str,
                  kind: str, rows: list[dict]) -> "pd.DataFrame":
    """Rows -> the parquet store's DataFrame shape (naive IST timestamps)."""
    import pandas as pd
    ist = [datetime.fromtimestamp(r["time"], tz=_SESSION_TZ).replace(tzinfo=None)
           for r in rows]
    return pd.DataFrame({
        "symbol": [symbol] * len(rows),
        "exchange": [exchange] * len(rows),
        "kind": [kind] * len(rows),
        "timeframe": [interval.lower()] * len(rows),
        "timestamp": ist,
        "open": [r["open"] for r in rows],
        "high": [r["high"] for r in rows],
        "low": [r["low"] for r in rows],
        "close": [r["close"] for r in rows],
        "volume": [r["volume"] for r in rows],
    })


class ParquetProvider:
    """Offline candles from the existing ParquetStorage store."""

    name = "parquet"

    def __init__(self, master: FuturesMaster, base_path: str | Path = "data/ohlcv"):
        self._master = master
        self._base_path = str(base_path)

    def candles(self, *, symbol: str, exchange: str, interval: str,
                start: datetime | None = None, end: datetime | None = None,
                limit: int | None = None) -> list[dict]:
        from ntrade.data.parquet_store import ParquetStorage
        store = ParquetStorage(self._base_path)
        tf = interval.lower()
        df = store.read(symbols=[symbol], start=start, end=end, timeframe=tf)
        if df.empty:
            return []
        return normalize_candles(df.to_dict("records"), limit=limit)

    def quote(self, *, symbol: str, exchange: str) -> dict:
        rows = self.candles(symbol=symbol, exchange=exchange, interval=Timeframe.D1, limit=1)
        if not rows:
            # Offline stores often lack D1 (the dhan write-through persists the
            # requested timeframe, typically 1m) — aggregate daily bars from the
            # stored intraday data so the header quote never fails offline.
            intraday = self.candles(symbol=symbol, exchange=exchange, interval="1m")
            rows = _aggregate_daily(intraday)
        if not rows:
            raise MarketDataError(f"no stored data for {symbol}")
        last = rows[-1]
        prev_rows = rows[:-1]  # already sorted ascending — previous session is rows[-2]
        prev_close = float(prev_rows[-1]["close"]) if prev_rows else last["close"]
        ltp = float(last["close"])
        change = ltp - prev_close
        return {
            "symbol": symbol,
            "exchange": exchange,
            "ltp": round(ltp, 2),
            "change": round(change, 2),
            "change_pct": round((change / prev_close * 100.0) if prev_close else 0.0, 2),
            "high": float(last["high"]),
            "low": float(last["low"]),
            "open": float(last["open"]),
            "prev_close": prev_close,
            "volume": int(last.get("volume") or 0),
            "oi": 0,
            "source": self.name,
        }


def _clamp_to_session(rows: list[dict], *, exchange: str,
                      interval: str) -> list[dict]:
    """Drop intraday bars whose IST start time is at/past the exchange's
    session close. Dhan ships bars that start after the close (1m to 15:39,
    5m to 15:35 on NSE) while the live pump stops exactly at the close — those
    ghost bars break the chart's right-edge seam. Daily bars anchor at
    midnight (before the open), so the clamp applies to intraday only."""
    if interval.lower() in DAILY_TIMEFRAMES:
        return rows
    cl = session_close(exchange)
    return [c for c in rows
            if datetime.fromtimestamp(c["time"], tz=_SESSION_TZ).time() < cl]


def _aggregate_daily(rows: list[dict]) -> list[dict]:
    """Aggregate intraday wire candles into per-IST-day bars (ascending)."""
    by_day: dict[date, dict] = {}
    for r in rows:
        day = datetime.fromtimestamp(r["time"], tz=_SESSION_TZ).date()
        d = by_day.get(day)
        if d is None:
            midnight = datetime.combine(day, time.min, tzinfo=_SESSION_TZ)
            by_day[day] = {"time": int(midnight.timestamp()), "open": r["open"],
                           "high": r["high"], "low": r["low"],
                           "close": r["close"], "volume": r["volume"]}
        else:
            d["high"] = max(d["high"], r["high"])
            d["low"] = min(d["low"], r["low"])
            d["close"] = r["close"]
            d["volume"] = d["volume"] + r["volume"]
    return [by_day[d] for d in sorted(by_day)]


class SyntheticProvider:
    """Deterministic seeded OHLCV generator for offline dev / replay / tests.

    Uses the same family of ideas as ``ntrade.sim.tick_simulator``: a seeded
    mean-reverting random walk over the IST session grid (09:15–15:30,
    weekdays only). Identical inputs produce identical candles, so replay
    behaviour and tests are stable. Clearly labelled ``source: "synthetic"``.
    """

    name = "synthetic"

    def __init__(self, master: FuturesMaster, days: int = DEFAULT_DAYS, seed: int = 7):
        self._master = master
        self._days = days
        self._seed = seed
        # Keyed by generation date so a server running across midnight anchors
        # to the new "last N sessions" instead of serving stale history forever.
        self._cache: dict[tuple[str, str, date], list[Candle]] = {}

    # ------------------------------------------------------------------ gen
    def _rng(self, symbol: str, interval: str) -> random.Random:
        key = f"{symbol}|{interval}|{self._seed}".encode()
        digest = int.from_bytes(hashlib.md5(key).digest()[:8], "big")
        return random.Random(digest)

    def _base_price(self, root: str) -> float:
        return _base_price(root)

    def _session_days(self, floor: date | None = None) -> list[date]:
        """Weekday sessions covering at least ``self._days`` sessions, extended
        backward to include ``floor`` when a chart window wider than the
        default requests it (a wide request must not be silently truncated)."""
        need = max(self._days, 1)
        if floor is not None:
            # Lazy extension is bounded by the history horizon so ancient
            # ranges keep the real providers' "no data" contract — but a
            # configured `self._days` above the cap is never truncated.
            need = max(need, min((date.today() - floor).days * 5 // 7 + 2,
                                 MAX_SYNTH_SESSIONS))
        days: list[date] = []
        d = date.today()
        while len(days) < need:
            if d.weekday() < 5:  # Mon–Fri
                days.append(d)
            d -= timedelta(days=1)
        return days[::-1]

    def _series(self, symbol: str, interval: str,
                floor: date | None = None) -> list[Candle]:
        key = (symbol, interval, floor or date.today())
        if key in self._cache:
            return self._cache[key]
        root = symbol.split()[0].upper()
        base = self._base_price(root)
        rng = self._rng(symbol, interval)
        span = _INTERVAL_MINUTES[interval]
        bar_span = timedelta(minutes=span) if span < 375 else timedelta(minutes=375)
        out: list[Candle] = []
        price = base
        for day in self._session_days(floor):
            # Daily bars anchor at midnight IST, matching Dhan's daily history
            # and the live pump's 1D grid — intraday bars stay on the
            # session-open grid.
            t0 = (datetime.combine(day, time.min, tzinfo=_SESSION_TZ)
                  if span >= _SESSION_MINUTES
                  else datetime.combine(day, _SESSION_OPEN, tzinfo=_SESSION_TZ))
            n_bars = _SESSION_MINUTES // span
            for k in range(n_bars):
                ret = rng.uniform(-0.0035, 0.0035) * (span ** 0.5) + rng.uniform(-0.0002, 0.0002)
                close = max(price * (1.0 + ret), 0.01)
                gap = 1.0 + rng.uniform(-0.0004, 0.0004) if k else 1.0
                open_ = price * gap
                high = max(open_, close) * (1.0 + rng.uniform(0.0, 0.0018))
                low = min(open_, close) * (1.0 - rng.uniform(0.0, 0.0018))
                lot = self._contract_lot(symbol) or 25.0
                volume = int(lot * (30 + rng.uniform(0.0, 220.0)))
                out.append(Candle(
                    time=int((t0 + k * bar_span).timestamp()),
                    open=round(open_, 2), high=round(high, 2),
                    low=round(low, 2), close=round(close, 2),
                    volume=volume,
                ))
                price = close
        self._cache[key] = out
        return out

    def _contract_lot(self, symbol: str) -> float | None:
        contract = self._master.resolve(symbol)
        return contract.lot_size if contract and contract.lot_size else None

    # ------------------------------------------------------------------ data
    def candles(self, *, symbol: str, exchange: str, interval: str,
                start: datetime | None = None, end: datetime | None = None,
                limit: int | None = None) -> list[dict]:
        floor = start.date() if start is not None else None
        series = self._series(symbol, interval, floor)
        if start is not None or end is not None:
            start_ts = start.timestamp() if start else None
            end_ts = end.timestamp() if end else None
            series = [c for c in series
                      if (start_ts is None or c.time >= start_ts)
                      and (end_ts is None or c.time <= end_ts)]
        if not series:
            return []
        if limit is not None and len(series) > limit:
            series = series[-limit:]
        return [c.as_dict() for c in series]

    def quote(self, *, symbol: str, exchange: str) -> dict:
        rows = self.candles(symbol=symbol, exchange=exchange, interval=Timeframe.MIN, limit=1)
        if not rows:
            raise MarketDataError(f"no data for {symbol}")
        last = rows[-1]
        prev_rows = self.candles(symbol=symbol, exchange=exchange, interval=Timeframe.MIN, limit=2)
        prev_close = float(prev_rows[-2]["close"]) if len(prev_rows) > 1 else last["close"]
        ltp = float(last["close"])
        change = ltp - prev_close
        return {
            "symbol": symbol,
            "exchange": exchange,
            "ltp": round(ltp, 2),
            "change": round(change, 2),
            "change_pct": round((change / prev_close * 100.0) if prev_close else 0.0, 2),
            "high": float(last["high"]),
            "low": float(last["low"]),
            "open": float(last["open"]),
            "prev_close": prev_close,
            "volume": int(last.get("volume") or 0),
            "oi": 0,
            "source": self.name,
        }


